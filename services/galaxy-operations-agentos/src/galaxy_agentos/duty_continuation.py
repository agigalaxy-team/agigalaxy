"""Native external-execution pauses resolved only by Node's original facts."""
import asyncio
from copy import deepcopy
from functools import wraps
import json
from uuid import UUID, uuid5, NAMESPACE_URL

from agno.models.message import Message
from agno.models.response import ToolExecution
from agno.run.base import RunStatus
from agno.run.requirement import RunRequirement

from .gateway import AuthorityDenied


WRITE_TOOLS = frozenset({"execute_operation", "manage_ai_role", "manage_ai_prompt"})
DECISION_STATES = frozenset({"completed", "failed", "rejected", "cancelled", "no-action"})
DECISION_BASES = frozenset({"manual-pause-read-again", "persisted-domain-operation-receipt", "original-operation-query",
    "persisted-ai-role-delegation-event", "persisted-human-decision"})


def call_reference(task_id, run_id, provider_call_id):
    return str(uuid5(NAMESPACE_URL, "galaxy-duty:" + task_id + ":" + run_id + ":" + provider_call_id))


def with_duty_pauses(model, gateway=None):
    """Use Agno's post-tool barrier to stop before another model invocation.

    Tool output is generated by the closed Node transport, not model text.
    A waiting human action becomes a native external-execution requirement;
    only the original human/domain receipt may later resolve it.
    """
    response, aresponse = model.response, model.aresponse

    def mark(value, run):
        for tool in value.tool_executions or []:
            if tool.tool_name not in WRITE_TOOLS or not tool.tool_call_id or not isinstance(tool.result, str):
                continue
            try:
                result = json.loads(tool.result)
            except (ValueError, TypeError):
                continue
            if not isinstance(result, dict) or result.get("state") != "waiting-human":
                continue
            if run is not None and isinstance(run.metadata, dict):
                run.metadata.pop("manualPause", None)
                run.metadata.pop("manualResumeConsumed", None)
            try:
                UUID(result["operationId"])
            except (KeyError, TypeError, ValueError, AttributeError):
                raise AuthorityDenied("agentos_autonomy_original_receipt_invalid") from None
            tool.external_execution_required = True
            tool.external_execution_silent = True
            # An existing result would make native continuation preserve the
            # waiting response instead of applying the later original receipt.
            tool.result = None
            if run is not None:
                run.requirements = [req for req in run.requirements or []
                    if req.tool_execution and req.tool_execution.tool_call_id != tool.tool_call_id]
                run.requirements.append(RunRequirement(tool_execution=tool))

    def manual_marker(value, run):
        if gateway is None or run is None or not run.user_id or not run.run_id:
            return
        if any(not req.is_resolved() for req in run.requirements or []):
            return  # Existing human requirements always take precedence.
        task = (gateway.duty_authorize(run.user_id, operation="read") or {}).get("task") or {}
        if run.user_id != "autonomy:" + str(task.get("taskId") or "") or run.session_id != task.get("sessionId"):
            return
        control = task.get("manualPause") or {}
        if control.get("phase") != "requested" or control.get("nativeRunId") not in (None, run.run_id):
            return
        completion = task.get("completion") or {}
        if completion.get("disposition") in {"unknown", "waiting-human"}:
            return
        try:
            pause_id = str(UUID(control["pauseOperationId"]))
        except (KeyError, ValueError, TypeError, AttributeError):
            return
        for tool in value.tool_executions or []:
            if not tool.tool_call_id or not tool.tool_name or not isinstance(tool.result, str):
                continue
            try:
                result = json.loads(tool.result)
            except (ValueError, TypeError):
                continue
            if not isinstance(result, dict) or result.get("state") in {"unknown", "waiting-human"}:
                continue
            call_id = call_reference(task["taskId"], run.run_id, tool.tool_call_id)
            if call_id not in (control.get("eligibleCallIds") or []):
                continue
            tool.external_execution_required = True
            tool.external_execution_silent = True
            tool.result = None
            run.requirements = [req for req in run.requirements or [] if req.tool_execution and req.tool_execution.tool_call_id != tool.tool_call_id]
            run.requirements.append(RunRequirement(tool_execution=tool))
            run.metadata = {**(run.metadata or {}), "manualPause": {"pauseOperationId": pause_id, "checkpointCallIds": [call_id]}}
            run.metadata.pop("manualResumeConsumed", None)
            return

    def consumed(run):
        if gateway is None or run is None or not run.user_id or not run.run_id:
            return
        marker = (run.metadata or {}).get("manualPause") or {}
        if not isinstance(marker, dict) or not marker.get("pauseOperationId") or not marker.get("checkpointCallIds"):
            return
        task = (gateway.duty_authorize(run.user_id, operation="read") or {}).get("task") or {}
        control = task.get("manualPause") or {}
        if (run.user_id != "autonomy:" + str(task.get("taskId") or "") or run.session_id != task.get("sessionId")
                or control.get("phase") != "resuming" or control.get("nativeRunId") != run.run_id
                or control.get("pauseOperationId") != marker.get("pauseOperationId")
                or control.get("checkpointCallIds") != marker.get("checkpointCallIds")):
            return
        try:
            resume_id = str(UUID(control["resumeOperationId"]))
        except (KeyError, ValueError, TypeError, AttributeError):
            return
        ids = marker.get("checkpointCallIds")
        if not isinstance(ids, list) or len(ids) != 1:
            return
        matched = [r for r in run.requirements or [] if r.tool_execution and r.tool_execution.tool_call_id
            and call_reference(task["taskId"], run.run_id, r.tool_execution.tool_call_id) == ids[0]]
        if len(matched) != 1 or not matched[0].is_resolved() or matched[0].tool_execution.is_paused or matched[0].tool_execution.result is None:
            return
        fact = {**marker, "resumeOperationId": resume_id}
        run.metadata = {**(run.metadata or {}), "manualResumeConsumed": fact}
        try:
            gateway.duty_report(run.user_id, {"nativeRunId": run.run_id, "modelState": "running", "status": "running", "manualResumeConsumed": fact})
        except Exception:
            pass  # Native persistence can report the same closed marker again.

    @wraps(response)
    def paused(*args, **kwargs):
        consumed(kwargs.get("run_response"))
        checkpoint = kwargs.get("after_tool_results")
        def after(value):
            run = kwargs.get("run_response")
            mark(value, run)
            manual_marker(value, run)
            if checkpoint is not None:
                checkpoint(value)
        kwargs["after_tool_results"] = after
        return response(*args, **kwargs)

    @wraps(aresponse)
    async def apaused(*args, **kwargs):
        await asyncio.to_thread(consumed, kwargs.get("run_response"))
        checkpoint = kwargs.get("after_tool_results")
        async def after(value):
            run = kwargs.get("run_response")
            mark(value, run)
            await asyncio.to_thread(manual_marker, value, run)
            if checkpoint is not None:
                await checkpoint(value)
        kwargs["after_tool_results"] = after
        return await aresponse(*args, **kwargs)

    model.response, model.aresponse = paused, apaused
    return model


def pending_tools(run):
    raw = run.to_dict() if hasattr(run, "to_dict") else run
    metadata = raw.get("metadata") or {}
    marker = metadata.get("manualPause") if isinstance(metadata, dict) else None
    task_id = metadata.get("taskId") if isinstance(metadata, dict) else None
    run_id = raw.get("run_id")
    ids = marker.get("checkpointCallIds") if isinstance(marker, dict) else None
    def selected(tool):
        if tool.get("tool_name") in WRITE_TOOLS:
            return True
        return (isinstance(ids, list) and len(ids) == 1 and isinstance(task_id, str)
            and isinstance(run_id, str) and call_reference(task_id, run_id, tool["tool_call_id"]) == ids[0])
    return [tool for tool in (raw or {}).get("tools") or [] if isinstance(tool, dict)
        and tool.get("external_execution_required") is True and isinstance(tool.get("tool_call_id"), str)
        and selected(tool)]


def continuation_tools(task, run):
    raw = run.to_dict() if hasattr(run, "to_dict") else run
    status = str(getattr((raw or {}).get("status"), "value", (raw or {}).get("status")) or "").upper()
    if (status != "PAUSED" or raw.get("agent_id") != "galaxy-duty"
            or raw.get("session_id") != task["sessionId"] or raw.get("user_id") != "autonomy:" + task["taskId"]):
        raise AuthorityDenied("agentos_autonomy_run_not_continuable")
    pending = pending_tools(raw)
    context = task.get("continuation") or {}
    marker = (raw.get("metadata") or {}).get("manualPause")
    if context.get("manualPause") is True:
        if not isinstance(marker, dict) or marker.get("pauseOperationId") != context.get("pauseOperationId"):
            raise AuthorityDenied("agentos_autonomy_original_receipt_invalid")
    decisions = context.get("decisions")
    if context.get("allowed") is not True or not pending or not isinstance(decisions, list):
        raise AuthorityDenied("agentos_autonomy_human_decision_required")
    by_call = {}
    for item in decisions:
        if not isinstance(item, dict) or item.get("callId") in by_call:
            raise AuthorityDenied("agentos_autonomy_original_receipt_invalid")
        try:
            if str(UUID(item["operationId"])) != item["operationId"]:
                raise ValueError()
        except (KeyError, TypeError, ValueError, AttributeError):
            raise AuthorityDenied("agentos_autonomy_original_receipt_invalid") from None
        if item.get("state") not in DECISION_STATES or item.get("basis") not in DECISION_BASES:
            raise AuthorityDenied("agentos_autonomy_original_receipt_invalid")
        by_call[item.get("callId")] = item
    tools = []
    for original in pending:
        call_id = call_reference(task["taskId"], raw["run_id"], original["tool_call_id"])
        decision = by_call.get(call_id)
        if decision is None:
            raise AuthorityDenied("agentos_autonomy_human_decision_required")
        fact = {key: decision[key] for key in ("operationId", "state", "basis")}
        fact["originalOperation"] = True
        if context.get("manualPause") is True:
            fact["manualPause"] = True
        else:
            fact["humanDecision"] = True
        tools.append({"tool_call_id": original["tool_call_id"], "tool_name": original["tool_name"],
            "tool_args": {}, "external_execution_required": True, "external_execution_silent": True,
            "result": json.dumps(fact, ensure_ascii=False, allow_nan=False)})
    return tools


def rehydrate_paused(run, *, task, instructions, tools, model_metadata=None):
    """Rebuild a purpose-bound continuation without retaining fetched bodies.

    Native retains the original IDs, metrics and pending requirement. The
    current trusted factory supplies the task's versioned instructions again;
    Node supplies original-operation facts. No private chat/evidence archive
    or caller-supplied prompt is needed to continue the same native run.
    """
    continuation_tools(task, run)  # revalidate at claim, after HTTP acceptance
    restored = deepcopy(run)
    previous_metadata = restored.metadata or {}
    current_version = (model_metadata or {}).get("modelSettingsVersion")
    if isinstance(current_version, str):
        versions = list(previous_metadata.get("modelSettingsVersions") or [])
        old_version = previous_metadata.get("modelSettingsVersion")
        for version in (old_version, current_version):
            if isinstance(version, str) and version not in versions:
                versions.append(version)
        if len(versions) > 32:
            raise AuthorityDenied("agentos_autonomy_model_versions_limit")
        restored.metadata = {**previous_metadata, "modelSettingsVersion": current_version, "modelSettingsVersions": versions}
    resolved = {tool["tool_call_id"]: ToolExecution.from_dict(tool) for tool in tools}
    restored.tools = [resolved.get(tool.tool_call_id, tool) for tool in restored.tools or []]
    # Agno's provided-RunOutput continuation path consumes the object's own
    # tools, unlike the run_id path which applies the separate requirements.
    restored.requirements = [RunRequirement(tool_execution=tool) for tool in resolved.values()]
    if restored.metrics is not None:
        previous = (restored.metadata or {}).get("activeDurationBefore", 0)
        elapsed = restored.metrics.duration
        if type(previous) in {float, int} and type(elapsed) in {float, int} and previous >= 0 and elapsed >= 0:
            restored.metadata = {**(restored.metadata or {}), "activeDurationBefore": previous + elapsed}
        restored.metrics.start_timer()
    continuation = "手动暂停已解除；按当前权限接续，原读取需要重新读取" if (task.get("continuation") or {}).get("manualPause") is True else "原任务已记录的人工决定；按当前权限接续"
    restored.messages = [Message(role="system", content="\n".join(instructions)),
        Message(role="user", content=json.dumps({"taskId": task["taskId"], "continuation": continuation}, ensure_ascii=False)),
        Message(role="assistant", tool_calls=[{"id": tool["tool_call_id"], "type": "function",
            "function": {"name": tool["tool_name"], "arguments": "{}"}} for tool in tools])]
    restored.status = RunStatus.paused
    return restored
