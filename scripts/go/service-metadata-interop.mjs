// Original public discovery verifier against the isolated Go HTTP service.
import {readFile} from 'node:fs/promises';
import {join,isAbsolute} from 'node:path';
import assert from 'node:assert/strict';
import {verifyEnvelope} from '../../packages/galaxy-client/src/verification/envelope.mjs';
import {digest} from '../../packages/galaxy-contracts/src/digest.mjs';
const origin=new URL(process.env.GALAXY_GO_TEST_DEVICE_ORIGIN??'');
if(origin.protocol!=='http:'||origin.hostname!=='127.0.0.1')throw Error('isolated loopback HTTP required');
const dir=process.env.GALAXY_GO_TEST_DEVICE_DIR;if(!isAbsolute(dir??''))throw Error('absolute disposable directory required');
const endpoint='https://device.example.invalid',now=2000000000;
const roots=JSON.parse(await readFile(join(dir,'root-pins.json'),'utf8'));
const rootPins=new Map(roots.keys.map(k=>[k.kid,k]));
const keysResponse=await fetch(origin.origin+'/.well-known/galaxy-signing-keys.json');
assert.equal(keysResponse.status,200);
const ring=await keysResponse.json();assert.deepEqual(Object.keys(ring),['signed']);
const openedKeys=await verifyEnvelope(ring.signed,{type:'keyring',issuer:endpoint,audience:endpoint,trustedKeys:rootPins,now,maxAge:86400});
assert.equal(openedKeys.data.version,1);assert.equal(openedKeys.data.endpoint,endpoint);assert.ok(Number.isSafeInteger(openedKeys.data.sequence)&&openedKeys.data.sequence>0);
assert.ok(Array.isArray(openedKeys.data.keys)&&openedKeys.data.keys.length>0);
const verifiedKeys=new Map(openedKeys.data.keys.map(key=>[key.kid,{...key,trustedUntil:openedKeys.expiresAt}]));
const response=await fetch(origin.origin+'/.well-known/galaxy-network.json');assert.equal(response.status,200);
const document=await response.json();assert.deepEqual(Object.keys(document),['signed']);
const checked=await verifyEnvelope(document.signed,{type:'manifest',issuer:endpoint,audience:endpoint,trustedKeys:verifiedKeys,now,maxAge:300});
assert.equal(checked.data.endpoint,endpoint);assert.equal(checked.data.networkType,process.argv[2]??'official');assert.equal(checked.data.signingKeyId,checked.kid);assert.equal(checked.data.revocationPath,'/v1/signing-keys/status');
assert.equal(checked.data.policy.automaticUpload,false);assert.equal(checked.data.policy.privateKeyCustody,'client');assert.equal(new URL(checked.data.policy.url).origin,endpoint);
assert.ok(Array.isArray(checked.data.capabilities));if(checked.data.networkType==='hub')assert.equal(checked.data.hub.profile,'galaxy-hub/1');
assert.equal(response.headers.get('etag'),'"'+digest(document.signed)+'"');
assert.equal(response.headers.get('cache-control'),'public, max-age=60, must-revalidate');
assert.deepEqual(await (await fetch(origin.origin+'/v1/policy')).json(),checked.data.policy);
const status=await (await fetch(origin.origin+'/v1/signing-keys/status')).json();
assert.deepEqual(status,{keys:roots.keys.map(({kid,revoked,notBefore,notAfter})=>({kid,revoked,notBefore,notAfter})),trustSource:'client-pinned-configuration',checkedAt:now});
assert.equal((await fetch(origin.origin+'/.well-known/galaxy-network.json',{headers:{'If-None-Match':response.headers.get('etag')}})).status,304);
console.log(JSON.stringify({state:"verified",networkType:checked.data.networkType,keys:status.keys.length}));
