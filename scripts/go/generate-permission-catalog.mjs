import {operationsAiActionRegistry,aiWorkPreparationRegistry,aiQueryPermissions,aiAutonomousPermissions} from '../../packages/galaxy-contracts/src/operations-ai-action-registry.mjs';
import {writeFile} from 'node:fs/promises';
import {operationsPermissionCodes,operationsPermissionCatalog} from '../../packages/galaxy-contracts/src/operations-permission-catalog.mjs';
import {managementMaintainerPermissionCodes} from '../../packages/galaxy-contracts/src/operations-management-maintainer-actions.mjs';
import {agentOsQueryViews} from '../../packages/galaxy-contracts/src/operations-agentos-query-schema.mjs';
import {agentOsQueryReadAction} from '../../packages/galaxy-contracts/src/operations-agentos-query-access.mjs';
const codes=[...operationsPermissionCodes];
if(new Set(codes).size!==codes.length||codes.some(code=>typeof code!=='string'||!/^[a-z][a-z0-9.-]{0,99}$/.test(code)))throw Error('invalid source permission catalog');
const list=values=>values.map(value=>'\t'+JSON.stringify(value)+',').join('\n');
await writeFile(new URL('../../go/internal/access/catalog.gen.go',import.meta.url),`// Code generated by scripts/go/generate-permission-catalog.mjs; DO NOT EDIT.
// Source is the current shared permission catalog, not inferred Go privileges.
package access

var permissionCodes=[]string{
${list(codes)}
}
var maintainerCodes=[]string{
${list(managementMaintainerPermissionCodes)}
}
func knownPermission(code string)bool{return contains(permissionCodes,code)}
`);

// Preserve the original metadata and JSON field order used by catalog leases.
await writeFile(new URL('../../go/internal/operationspermissions/catalog.gen.go',import.meta.url),`// Code generated by scripts/go/generate-permission-catalog.mjs; DO NOT EDIT.
// Same source and ordering as access/catalog.gen.go.
package operationspermissions

const catalogJSON=${JSON.stringify(JSON.stringify(operationsPermissionCatalog))}
const maintainerJSON=${JSON.stringify(JSON.stringify(managementMaintainerPermissionCodes))}
`);


await writeFile(new URL('../../go/internal/operationsai/catalog.gen.go',import.meta.url),`// Code generated by scripts/go/generate-permission-catalog.mjs; DO NOT EDIT.
// Current action facts, never inferred authority from a position name.
package operationsai

const actionJSON=${JSON.stringify(JSON.stringify({actions:operationsAiActionRegistry,preparation:aiWorkPreparationRegistry,query:aiQueryPermissions,autonomous:aiAutonomousPermissions}))}
const queryJSON=${JSON.stringify(JSON.stringify(Object.fromEntries(Object.entries(agentOsQueryViews).map(([module,views])=>[module,views.map(view=>({view,permission:agentOsQueryReadAction(module,{view})}))]))))}
`);
